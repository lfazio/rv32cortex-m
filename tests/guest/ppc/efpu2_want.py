"""The inputs efpu2.c runs and the answers it checks, worked out here.

efpu2.c is compiled by clang for EFPU2, so every operation in it is an
e200z7 floating-point instruction; this computes the same operations
with tests/ppc-check/efpu.py's model, which works in Python's exact
rationals and shares nothing with the emulator's C. The inputs are
written into the header too, so the two cannot disagree about them.
Regenerate after changing anything here:

    python3 tests/guest/ppc/efpu2_want.py > tests/guest/ppc/efpu2_want.h

The values are chosen for what EFPU2 does differently from IEEE --
infinities and NaNs in give the largest normal out, denormals count as
zero, overflow saturates, underflow is zero -- and for what the
emulator's integer fast path depends on: cancellation, exponents 39
and 40 apart, carries, exact and inexact quotients.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "ppc-check"))
import efpu  # noqa: E402

VALUES = [
    0x00000000, 0x80000000,  # zeros
    0x00000001, 0x807FFFFF,  # denormals: zeros of their sign
    0x00800000,              # the smallest normal
    0x7F7FFFFF, 0xFF7FFFFF,  # the largest
    0x7F800000, 0xFF800000,  # infinities: defaults, not results
    0x7FC00000,              # a NaN
    0x3F800000, 0xBF800000,  # 1, -1
    0x3FC00000, 0x40100000,  # 1.5, 2.25
    0x3F800001,              # 1 + ulp
    0x33800000,              # 2^-24: half an ulp of 1
    0x2B800001,              # just over 2^-40: past the exact sum
    0x2C000001,              # just over 2^-39: inside it
    0x4B7FFFFF, 0x4B000001,  # carries and cancellation near 2^23
    0x40490FDB,              # pi
    0xC2F6E979,              # -123.456
]

FLOATS = [  # to integers
    0x00000000, 0x3F000000, 0x3F400000, 0xBF400000, 0x4F000000,
    0x4F800000, 0xCF000000, 0xCF000001, 0x7F800000, 0x7FC00000,
    0x00000001, 0x4B7FFFFF, 0x447A0000, 0xC47A0000,
]
INTS = [  # from integers
    0, 1, 0xFFFFFFFF, 0x7FFFFFFF, 0x80000000, 0x01000001, 0x00FFFFFF,
    16777217, 0x12345678, 0xFFFFFF85,
]
POLY = [0x3F800000, 0xBE2AAAAB, 0x3C088889, 0xB9500D01]  # sin's Taylor terms
XS = [0x3F000000, 0x3F800000, 0x40000000, 0xBFC00000, 0x3DCCCCCD]  # ordinary

STICKY = efpu.FINXS | efpu.FINVS | efpu.FDBZS | efpu.FUNFS | efpu.FOVFS
spefscr = 0


def op(mn, a=0, b=0):
    """One instruction through the model, in the order efpu2.c runs it."""
    global spefscr
    rd, spefscr, irq, cr = efpu.model(mn, spefscr, a, b, 0)
    assert irq == 0, (mn, a, b)
    return rd, cr


def arr(name, vals):
    body = ",".join("\n    0x%08Xu" % v if i % 6 == 0 else " 0x%08Xu" % v
                    for i, v in enumerate(vals))
    return "static const unsigned int %s[%d] = {%s\n};\n" % (name, len(vals), body)


out = []
out.append(arr("IN_V", VALUES))
want_arith = []
for a in VALUES:
    for b in VALUES:
        for mn in ("efsadd", "efssub", "efsmul", "efsdiv"):
            want_arith.append(op(mn, a, b)[0])
want_cmp = []
for a in VALUES:
    for b in VALUES:
        m = 0
        for bit, mn in enumerate(("efscmplt", "efscmpgt", "efscmpeq")):
            if op(mn, a, b)[1]:
                m |= 1 << bit
        want_cmp.append(m)
out.append(arr("WANT_ARITH", want_arith))
out.append(arr("WANT_CMP", want_cmp))

out.append(arr("IN_F", FLOATS))
want_to = []
for f in FLOATS:
    want_to.append(op("efsctsiz", 0, f)[0])
    want_to.append(op("efsctuiz", 0, f)[0])
out.append(arr("WANT_TO_INT", want_to))

out.append(arr("IN_I", INTS))
want_from = []
for i in INTS:
    want_from.append(op("efscfsi", 0, i)[0])
    want_from.append(op("efscfui", 0, i)[0])
out.append(arr("WANT_FROM_INT", want_from))

out.append(arr("IN_POLY", POLY))
out.append(arr("IN_X", XS))
# The sticky bits so far, and then cleared: the polynomial's inputs are
# all ordinary, so afterwards only FINXS may be set -- the check that
# all five being set above cannot make.
sticky_all = spefscr & STICKY
spefscr = 0
want_poly = []
for x in XS:
    t = POLY[3]
    for c in (POLY[2], POLY[1], POLY[0]):
        t = op("efsmul", t, x)[0]
        t = op("efsadd", t, c)[0]
    want_poly.append(t)
out.append(arr("WANT_POLY", want_poly))

checks = len(want_arith) + len(want_cmp) + len(want_to) + len(want_from) + len(want_poly) + 2

print("/* SPDX-License-Identifier: Apache-2.0 */")
print("/* Generated by efpu2_want.py; do not edit. */")
print("#ifndef PPC_EFPU2_WANT_H")
print("#define PPC_EFPU2_WANT_H")
print("#define WANT_STICKY 0x%08Xu" % sticky_all)
print("#define WANT_POLY_STICKY 0x%08Xu" % (spefscr & STICKY))
print("#define WANT_CHECKS %du /* 0x%08x, what the terminator reports */" % (checks, checks))
print("".join(out), end="")
print("#endif")
